param(
    [switch]$Yara,
    [switch]$SkipBuild,
    [switch]$PackageOnly
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$pluginSource = Join-Path $repoRoot 'gralloch-plugin'
$binary = Join-Path $pluginSource 'bin\gralloch-mcp.exe'
if (-not $PackageOnly -and -not (Get-Command codex -ErrorAction SilentlyContinue)) {
    throw 'codex CLI not found. Install Codex CLI and rerun this script.'
}
if ($SkipBuild -and $Yara) {
    throw 'Choose -SkipBuild to reuse the existing binary, or -Yara to rebuild with YARA.'
}
if (-not $SkipBuild) {
    & (Join-Path $pluginSource 'gralloch-mcp\build-windows.ps1') -Yara:$Yara
}
if (-not (Test-Path -LiteralPath $binary -PathType Leaf)) {
    throw 'Server executable missing. Build it first or rerun without -SkipBuild.'
}

# Stage only runtime files. Never distribute case data, Git metadata, build
# directories, Claude hooks, or the developer's .codex/config.toml.
$packageParent = Join-Path $repoRoot '.codex-package'
$packageRoot = Join-Path $packageParent 'gralloch'
$marker = Join-Path $packageRoot '.gralloch-generated-package'
if ((Test-Path -LiteralPath $packageParent) -and
    (Get-Item -LiteralPath $packageParent).Attributes.HasFlag([System.IO.FileAttributes]::ReparsePoint)) {
    throw "Package parent must not be a link: $packageParent"
}
if (Test-Path -LiteralPath $packageRoot) {
    $expected = [System.IO.Path]::GetFullPath((Join-Path $repoRoot '.codex-package\gralloch'))
    $resolved = (Resolve-Path -LiteralPath $packageRoot).Path
    if ($resolved -ne $expected -or -not (Test-Path -LiteralPath $marker -PathType Leaf) -or
        (Get-Item -LiteralPath $packageRoot).Attributes.HasFlag([System.IO.FileAttributes]::ReparsePoint)) {
        throw "Refusing to replace an unrecognized package directory: $packageRoot"
    }
    Remove-Item -LiteralPath $packageRoot -Recurse -Force
}
New-Item -ItemType Directory -Force -Path $packageRoot | Out-Null
Set-Content -LiteralPath $marker -Value 'Generated by scripts/install-codex.ps1' -Encoding ascii

foreach ($relative in @('.codex-plugin', '.agents\skills', 'gralloch-plugin\bin',
    'gralloch-plugin\skills', 'gralloch-plugin\scripts', 'gralloch-plugin\schemas')) {
    New-Item -ItemType Directory -Force -Path (Join-Path $packageRoot $relative) | Out-Null
}
foreach ($relative in @('README.md', 'LICENSE', '.mcp.codex.json', '.codex-plugin\plugin.json',
    '.agents\skills\gralloch\SKILL.md', 'gralloch-plugin\bin\gralloch-mcp.exe')) {
    $destination = Join-Path $packageRoot $relative
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $destination) | Out-Null
    Copy-Item -LiteralPath (Join-Path $repoRoot $relative) -Destination $destination
}
foreach ($relative in @('skills', 'scripts', 'schemas')) {
    Get-ChildItem -LiteralPath (Join-Path $pluginSource $relative) | ForEach-Object {
        Copy-Item -LiteralPath $_.FullName -Destination (Join-Path $packageRoot "gralloch-plugin\$relative") -Recurse
    }
}
Write-Host "Prepared self-contained plugin: $packageRoot"
if ($PackageOnly) { return }

& codex plugin marketplace add $repoRoot
if ($LASTEXITCODE -ne 0) { throw 'Codex marketplace registration failed.' }
& codex plugin add 'gralloch@gralloch-codex'
if ($LASTEXITCODE -ne 0) { throw 'Codex plugin installation failed.' }
Write-Host 'Installed. Start a new local Codex chat and run:'
Write-Host '$gralloch:gralloch "C:\samples\app.exe" --profile understand --cases-root "C:\analysis\cases"'
