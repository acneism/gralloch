param(
    [Parameter(Mandatory = $true)][string]$CasesRoot
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$server = Join-Path $repoRoot 'gralloch-plugin\bin\gralloch-mcp.exe'
if (-not (Test-Path -LiteralPath $server -PathType Leaf)) {
    throw 'Build the server first: gralloch-plugin\gralloch-mcp\build-windows.ps1 [-Yara]'
}
if (-not [System.IO.Path]::IsPathRooted($CasesRoot)) {
    throw 'CasesRoot must be an absolute path outside the repository.'
}
$casePath = [System.IO.Path]::GetFullPath($CasesRoot)
$repoPrefix = $repoRoot.TrimEnd('\', '/') + [System.IO.Path]::DirectorySeparatorChar
if ($casePath.TrimEnd('\', '/') -ieq $repoRoot -or $casePath.StartsWith($repoPrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw 'CasesRoot must be outside the repository.'
}

# JSON strings are also valid TOML basic strings for these Windows paths.
$serverToml = ConvertTo-Json -InputObject $server -Compress
$rootToml = ConvertTo-Json -InputObject $repoRoot -Compress
$casesToml = ConvertTo-Json -InputObject $casePath -Compress
$config = @"
# Generated by scripts/setup-codex.ps1. Local absolute paths; do not commit.
[mcp_servers.gralloch]
command = $serverToml
cwd = $rootToml
startup_timeout_sec = 20
tool_timeout_sec = 600

[mcp_servers.gralloch.env]
RUST_LOG = "info"
GRALLOCH_CASES_ROOT = $casesToml
"@
$configDir = Join-Path $repoRoot '.codex'
$configPath = Join-Path $configDir 'config.toml'
if (Test-Path -LiteralPath $configPath) {
    throw "Configuration already exists at $configPath. Merge the gralloch MCP settings manually; no files were changed."
}
New-Item -ItemType Directory -Force -Path $configDir | Out-Null
[System.IO.File]::WriteAllText($configPath, $config + "`n", (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Created $configPath. Open this repository as a trusted project in Codex, then start a new chat."
